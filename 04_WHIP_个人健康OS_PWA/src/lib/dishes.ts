import type { Food } from './types';
export interface Dish {
  id: string;
  name: string;
  english: string;
  category: string;
  description: string;
  food?: Food;
  defaultGrams: number;
  photoLabel: string;
}
const hk =
  'https://www.cfs.gov.hk/english/programme/programme_rafs/programme_rafs_n_01_01_nvic.html';
function hkFood(
  id: string,
  name: string,
  english: string,
  kcal: number,
  p: number,
  c: number,
  f: number,
  sugar: number,
  fiber: number | null,
  sodium: number,
): Food {
  return {
    id,
    name,
    english,
    aliases: name + ' ' + english,
    basis: 'g',
    quality: 'reference',
    source: '香港食安中心 · 2006 熟食样本参考（不同餐厅会变化）',
    sourceId: 'RAFS22 AnnexIV / ' + name,
    sourceURL: hk,
    retrievedAt: '2026-10-22',
    nutrients: { calories: kcal, protein: p, carbs: c, fat: f, sugar, fiber, sodium },
    servings: [],
  };
}
function myFood(
  id: string,
  name: string,
  english: string,
  sourceId: string,
  kcal: number,
  p: number,
  c: number,
  f: number,
  fiber: number,
  sodium: number,
): Food {
  return {
    id,
    name,
    english,
    aliases: name + ' ' + english,
    basis: 'g',
    quality: 'reference',
    source: '马来西亚卫生部 MyFCD1997 · 熟食参考，非餐厅实测',
    sourceId,
    sourceURL:
      'https://myfcd.moh.gov.my/myfcd97/index.php/site/detail_product/' +
      sourceId +
      '/0/10/-1/0/0/',
    retrievedAt: '2026-10-22',
    nutrients: { calories: kcal, protein: p, carbs: c, fat: f, sugar: null, fiber, sodium },
    servings: [],
  };
}
