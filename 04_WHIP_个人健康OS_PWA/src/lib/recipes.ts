export function recipeNutrients(parts: RecipePart[], yieldGrams: number): Nutrients {
  if (!Number.isFinite(yieldGrams) || yieldGrams < 1 || yieldGrams > 100000)
    throw Error('请输入有效成品重量');
  if (!parts.some((p) => p.grams > 0)) throw Error('配方至少需要一项实际食材');
  const keys = [
    'calories',
    'protein',
    'carbs',
    'fat',
    'fiber',
    'sugar',
    'sodium',
    'saturatedFat',
    'caffeine',
  ] as const;
  return Object.fromEntries(
    keys.map((k) => {
      let sum = 0;
      let known = true;
      for (const p of parts) {
        const food = ingredientByKey.get(p.key)?.food;
        if (!food || !Number.isFinite(p.grams) || p.grams < 0 || p.grams > 10000)
          throw Error('配方食材或重量无效');
        if (p.grams === 0) continue;
        const value = food.nutrients[k];
        if (value == null) known = false;
        else sum += (value * p.grams) / 100;
      }
      return [k, known ? (sum * 100) / yieldGrams : null];
    }),
  ) as unknown as Nutrients;
}
export function recipeFood(
  recipe: RecipeDish,
  parts = recipe.parts,
  yieldGrams = recipe.yieldGrams,
  id = recipe.id,
): Food {
  return {
    id,
    name: recipe.name,
    english: recipe.english,
    aliases: recipe.name + ' ' + recipe.english,
    basis: 'g',
    quality: 'estimate',
    source:
      '示范配方估算：' +
      parts.map((p) => `${ingredientByKey.get(p.key)!.food.name} ${p.grams}g`).join('；'),
    sourceId: `USDA食材加总 / 假设成品${yieldGrams}g`,
    nutrients: recipeNutrients(parts, yieldGrams),
    servings: [],
    retrievedAt: '2026-10-23',
  };
}
